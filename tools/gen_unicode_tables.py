#!/usr/bin/env python3
"""Generate include/fasttok_unicode.hpp: a two-stage lookup table that maps every
Unicode code point to the character-class bits the pre-tokenizer needs.

The classes mirror what the tiktoken regexes use (Rust `regex` semantics):
  F_L   \\p{L}                       (Lu Ll Lt Lm Lo)
  F_N   \\p{N}                       (Nd Nl No)
  F_WS  \\s                          (Unicode White_Space property)
  F_UP  [\\p{Lu}\\p{Lt}\\p{Lm}\\p{Lo}\\p{M}]   (o200k "upper-ish" set)
  F_LO  [\\p{Ll}\\p{Lm}\\p{Lo}\\p{M}]         (o200k "lower-ish" set)
  F_NL  \\r or \\n

The Unicode version must match the one compiled into tiktoken's Rust regex crate.
Pass --ucd unicodedata2 to use the pip `unicodedata2` package (pin its version to
the Unicode version you need) instead of the Python stdlib tables.

Usage: gen_unicode_tables.py [--ucd unicodedata|unicodedata2] OUTPUT.hpp
"""
import argparse
import importlib

F_L, F_N, F_WS, F_UP, F_LO, F_NL = 1, 2, 4, 8, 16, 32

# Unicode White_Space property (stable since Unicode 6.3, when U+180E was removed).
WHITE_SPACE = set(range(0x09, 0x0E)) | {
    0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000}


def flags_for(ud, cp):
    if 0xD800 <= cp <= 0xDFFF:
        return 0  # surrogates never appear in valid UTF-8
    cat = ud.category(chr(cp))
    f = 0
    if cat[0] == "L":
        f |= F_L
    if cat[0] == "N":
        f |= F_N
    if cp in WHITE_SPACE:
        f |= F_WS
    if cat in ("Lu", "Lt", "Lm", "Lo") or cat[0] == "M":
        f |= F_UP
    if cat in ("Ll", "Lm", "Lo") or cat[0] == "M":
        f |= F_LO
    if cp in (0x0A, 0x0D):
        f |= F_NL
    return f


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd", default="unicodedata")
    ap.add_argument("out")
    args = ap.parse_args()
    ud = importlib.import_module(args.ucd)

    blocks, index, stage1 = [], {}, []
    for hi in range(0x110000 >> 8):
        blk = bytes(flags_for(ud, (hi << 8) | lo) for lo in range(256))
        if blk not in index:
            index[blk] = len(blocks)
            blocks.append(blk)
        stage1.append(index[blk])

    def rows(vals, per):
        return ",\n".join("  " + ",".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))

    stage2 = b"".join(blocks)
    with open(args.out, "w") as f:
        f.write("// Generated by tools/gen_unicode_tables.py -- do not edit.\n")
        f.write(f"// Unicode version: {ud.unidata_version} (source module: {args.ucd})\n")
        f.write("#pragma once\n#include <cstdint>\n\nnamespace fasttok { namespace ucd {\n\n")
        f.write(f'inline constexpr const char* kUnicodeVersion = "{ud.unidata_version}";\n')
        f.write(f"inline constexpr uint8_t F_L = {F_L}, F_N = {F_N}, F_WS = {F_WS}, "
                f"F_UP = {F_UP}, F_LO = {F_LO}, F_NL = {F_NL};\n\n")
        f.write(f"alignas(64) inline constexpr uint16_t kStage1[{len(stage1)}] = {{\n{rows(stage1, 24)}\n}};\n\n")
        f.write(f"alignas(64) inline constexpr uint8_t kStage2[{len(stage2)}] = {{\n{rows(list(stage2), 32)}\n}};\n\n")
        f.write("}}  // namespace fasttok::ucd\n")
    print(f"Unicode {ud.unidata_version}: {len(blocks)} unique blocks, "
          f"{len(stage1) * 2 + len(stage2)} bytes of tables -> {args.out}")


if __name__ == "__main__":
    main()
